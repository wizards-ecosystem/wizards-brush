"""Re-resolve the Remote GPU worker's hashed dependency closure.

Run via `make remote-gpu-lock`. It writes `scripts/remote-gpu-requirements.in`
(the resolved closure, readable) and `scripts/remote-gpu-requirements.lock`
(the same closure with hashes, which the Dockerfile installs with
`--require-hashes --only-binary=:all: --no-deps`).

Why the closure is resolved *from the app's lock*: both lanes load the same
model families through diffusers and transformers, and a worker on a different
diffusers than the app is how Qwen-Image-Edit-2511 ran for weeks on a release
that silently ignored its `zero_cond_t` flag. `uv export` of `uv.lock` is the
constraint set, so a shared package can only ever be at the version the app
already tests.

Why torch is not in it: the lock is installed `--no-deps`, and torch's CUDA
build is chosen in the Dockerfile (`TORCH_VERSION` / `TORCH_INDEX_URL`), whose
wheel brings its own `nvidia-*` libraries. Locking those from PyPI would pin the
cu13x set against a cu128 torch. They are resolved here so the versions agree,
then left out of the files.
"""
from __future__ import annotations

import pathlib
import re
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
IN = ROOT / "scripts" / "remote-gpu-requirements.in"
LOCK = ROOT / "scripts" / "remote-gpu-requirements.lock"

# The image's interpreter and platform. Hashes are of wheels for exactly this.
PYTHON = "3.12"
PLATFORM = "x86_64-manylinux_2_28"

# What the worker imports, plus the two runtime tools its pipelines call into
# (imageio-ffmpeg for export_to_video, sentencepiece/protobuf for tokenizers).
# Everything else in the closure is a dependency of one of these.
DIRECT = (
    "accelerate", "diffusers", "transformers", "peft", "safetensors",
    "huggingface-hub", "hf-xet", "tokenizers", "sentencepiece", "protobuf",
    "einops", "ftfy", "fastapi", "uvicorn", "pydantic", "pillow",
    "imageio", "imageio-ffmpeg", "scipy", "psutil",
)

# Provided by the torch install in the Dockerfile, never by this lock. setuptools
# is torch's too: torch 2.11 caps it below 82 while the app's lock has 84, and
# `pip check` in the image build is what caught the closure overriding it.
CUDA_SIDE = re.compile(
    r"^(torch|torchvision|numpy|triton|sympy|networkx|mpmath|setuptools"
    r"|nvidia-[a-z0-9-]+|cuda-[a-z0-9-]+)==",
    re.IGNORECASE,
)

IN_HEADER = """\
# Fully resolved non-Torch dependency closure for the Linux x86-64 / Python 3.12
# Remote GPU worker, at the versions the app's own uv.lock pins. Generated by
# `make remote-gpu-lock`; edit scripts/lock_remote_gpu.py, not this file.
# Torch, torchvision, numpy and Torch's CUDA libraries intentionally come from
# the Dockerfile's torch install.
"""

LOCK_HEADER = """\
# Generated from remote-gpu-requirements.in by `make remote-gpu-lock` (uv). Every
# package is explicit because installation uses --no-deps to preserve the base
# CUDA stack. Resolved for Python 3.12 / x86_64-manylinux_2_28 with
# --generate-hashes, --only-binary :all:, --no-annotate and --no-header.
"""


def _run(*args: str) -> str:
    return subprocess.run(args, check=True, capture_output=True, text=True, cwd=ROOT).stdout


def app_constraints(tmp: pathlib.Path) -> pathlib.Path:
    """Every version the app pins, as a constraints file.

    Local build tags (`+cu130`) are stripped: a constraint names a version, and
    the CUDA build is the Dockerfile's decision. Environment markers go too -
    this resolves for one platform.
    """
    raw = _run("uv", "export", "--frozen", "--no-hashes", "--no-emit-project", "--no-dev")
    lines = []
    for line in raw.splitlines():
        line = re.sub(r"\+cu\d+", "", line.split(" ;", 1)[0]).strip()
        if re.match(r"^[A-Za-z0-9_.-]+==", line):
            lines.append(line)
    out = tmp / "app-constraints.txt"
    out.write_text("\n".join(lines) + "\n")
    return out


def resolve(tmp: pathlib.Path) -> list[str]:
    """The hashed closure as lock entries, CUDA-side packages removed."""
    top = tmp / "direct.in"
    top.write_text("\n".join(DIRECT) + "\n")
    full = tmp / "full.lock"
    _run("uv", "pip", "compile", str(top), "-c", str(app_constraints(tmp)),
         "--python-version", PYTHON, "--python-platform", PLATFORM,
         "--only-binary", ":all:", "--generate-hashes", "--no-annotate", "--no-header",
         "-o", str(full))
    entries = re.split(r"\n(?=\S)", full.read_text().strip())
    kept = [e for e in entries if not CUDA_SIDE.match(e)]
    dropped = [e.splitlines()[0].rstrip(" \\") for e in entries if CUDA_SIDE.match(e)]
    print("left to the Dockerfile's torch install:", ", ".join(dropped))
    return kept


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="remote-gpu-lock.") as tmpdir:
        entries = resolve(pathlib.Path(tmpdir))
    names = [e.splitlines()[0].rstrip(" \\") for e in entries]
    IN.write_text(IN_HEADER + "\n".join(names) + "\n", encoding="utf-8")
    LOCK.write_text(LOCK_HEADER + "\n".join(entries) + "\n", encoding="utf-8")
    print(f"Wrote {IN.relative_to(ROOT)} and {LOCK.relative_to(ROOT)}: {len(names)} packages")
    for want in ("diffusers", "transformers", "huggingface-hub", "peft", "accelerate"):
        print("  ", next((n for n in names if n.startswith(want + "==")), f"{want}: MISSING"))


if __name__ == "__main__":
    main()
